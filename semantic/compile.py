"""Turn a Metric into SQL. One definition, one answer, every caller.

The compiler REFUSES rather than guesses. Asked to group by a column the
metric's table does not have, it raises - because compiling against a
column that merely shares a name is how a dashboard starts showing a
number nobody can explain.

Filter values are always bound as parameters, never pasted into the text,
even though the catalogue is generated by us rather than typed by a user.
"""

from __future__ import annotations

from semantic.discover import Metric

# Source tables are materialised under this prefix when the graph is built.
SRC = "s"


def qi(name: str) -> str:
    """Quote an identifier, doubling any embedded quote."""
    return '"' + str(name).replace('"', '""') + '"'


def compile_metric(m: Metric, group_by: str | None = None,
                   where: dict | None = None, limit: int = 100,
                   table_sql: str | None = None,
                   table_prefix: str = SRC) -> tuple[str, list]:
    """SQL for one metric.

    `table_sql` is how to address the table in THIS graph - ask
    knowledge_graph.build.table_ref for it. Without it the compiler has to
    guess a naming scheme, and the guess is only right for file sources.
    """
    where = where or {}

    allowed = set(m.dimensions) | ({m.time_column} if m.time_column else set())
    for col in [c for c in [group_by] if c] + list(where):
        if col not in allowed:
            raise KeyError(
                f"metric {m.name!r} reads {m.table!r}, which has no dimension "
                f"{col!r}; available: {', '.join(sorted(allowed)) or 'none'}")

    if m.agg == "count":
        expr = "count(*)"
    elif m.agg == "quantile_cont":
        expr = f"quantile_cont({qi(m.column)}, 0.99)"
    elif m.agg == "median":
        expr = f"median({qi(m.column)})"
    else:
        expr = f"{m.agg}({qi(m.column)})"

    table = table_sql or (qi(f"{table_prefix}_{m.table}")
                          if table_prefix else qi(m.table))

    select = [f"{qi(group_by)} AS grouped"] if group_by else []
    select.append(f"{expr} AS value")

    sql = [f"SELECT {', '.join(select)}", f"FROM {table}"]
    params: list = []
    if where:
        sql.append("WHERE " + " AND ".join(f"{qi(k)} = ?" for k in where))
        params = list(where.values())
    if group_by:
        sql.append(f"GROUP BY {qi(group_by)}")
        sql.append("ORDER BY value DESC NULLS LAST")
    sql.append(f"LIMIT {int(limit)}")
    return "\n".join(sql), params
